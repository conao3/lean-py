"""Print LeanPython/RuntimeExterns.lean: the C names the runtime implements."""

import inspect

from lean_python import runtime

names = sorted(
    n
    for n, v in vars(runtime).items()
    if callable(v) and not inspect.isclass(v) and not n.startswith("_") and n not in ("lean_py_extern",)
)
print("/-! C names of the functions the runtime `lean_python.runtime` provides. Generated by `make gen-externs`. -/")
print()
print("namespace LeanPython")
print()
print("def runtimeExterns : Array String := #[")
print(",\n".join(f'  "{n}"' for n in names))
print("]")
print()
print("end LeanPython")
